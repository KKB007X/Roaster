#!/usr/bin/env python3
"""Compile the two matvec shaders and embed them into kernels.c.

Usage (from the folder that contains kernels.c and shaders/):
    python3 shaders/embed_spv.py kernels.c

It needs ONE of these installed:  glslangValidator  (apt install glslang-tools)
                                  glslc             (apt install glslc, or the Vulkan SDK)
It rewrites everything between '/* BEGIN EMBEDDED SPIRV */' and '/* END EMBEDDED SPIRV */'
at the end of kernels.c. A backup is saved as kernels.c.bak.
"""
import os, shutil, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [("q4k_matvec.comp", "roaster_spv_q4k_v2"),
           ("q6k_matvec.comp", "roaster_spv_q6k_v2"),
           ("silu_mul.comp", "roaster_spv_silu_v1")]

def compile_shader(src, out):
    if shutil.which("glslangValidator"):
        cmd = ["glslangValidator", "-V", "--target-env", "vulkan1.1", src, "-o", out]
    elif shutil.which("glslc"):
        cmd = ["glslc", "--target-env=vulkan1.1", "-fshader-stage=compute", src, "-o", out]
    else:
        sys.exit("No shader compiler found. Install glslang-tools (glslangValidator) or glslc.")
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("Shader compile failed for %s:\n%s%s" % (src, r.stdout, r.stderr))

def c_array(name, data):
    assert len(data) % 4 == 0 and struct.unpack("<I", data[:4])[0] == 0x07230203, "not SPIR-V"
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    return ("const uint32_t %s[] = {\n%s\n};\nconst size_t %s_size = sizeof(%s);\n"
            % (name, "\n".join(lines), name, name))

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    target = sys.argv[1]
    text = open(target).read()
    b, e = "/* BEGIN EMBEDDED SPIRV */", "/* END EMBEDDED SPIRV */"
    if b not in text or e not in text:
        sys.exit("markers not found in " + target)
    blobs = []
    with tempfile.TemporaryDirectory() as tmp:
        for src, sym in SHADERS:
            path = os.path.join(HERE, src)
            if not os.path.exists(path):
                sys.exit("missing " + path)
            spv = os.path.join(tmp, src + ".spv")
            if os.environ.get("EMBED_SPV_DIR"):      # test hook: use precompiled files
                spv = os.path.join(os.environ["EMBED_SPV_DIR"], src + ".spv")
            else:
                compile_shader(path, spv)
            blobs.append(c_array(sym, open(spv, "rb").read()))
    block = (b + "\n/* AUTO-GENERATED by shaders/embed_spv.py from q4k_matvec.comp / q6k_matvec.comp / silu_mul.comp. Do not edit. */\n"
             + "".join(blobs) + e)
    head = text[:text.index(b)]
    tail = text[text.index(e) + len(e):]
    shutil.copyfile(target, target + ".bak")
    open(target, "w").write(head + block + tail)
    print("embedded %d shaders into %s (backup: %s.bak)" % (len(blobs), target, target))

main()
